//! Render and check `sys/include/rfork.h` from the Rust flag constants
//! (DSGN-02, D-12).  The Rust constants in `port/src/rfork.rs` are the
//! single source of truth: this module compiles that same file by
//! `#[path]`, renders the C statement of the interface, and refuses a
//! committed copy that is missing, empty or stale.
//!
//! Plain text generation — no crate.  Errors name the file and the
//! regenerate command, in the `uregcheck` house style.

use std::fs;
use std::path::Path;

use crate::Result;

#[path = "../../port/src/rfork.rs"]
#[allow(dead_code)]
mod flags;

pub const HEADER_PATH: &str = "sys/include/rfork.h";

/// The whole of `sys/include/rfork.h`: the banner, the `RF*` enum and the
/// `rfork()` declaration.  No include guard — Harvey's `libc.h` has none
/// and this file is not meant to be included beside it.
pub fn render() -> String {
    let mut out = String::new();
    out.push_str(concat!(
        "/*\n",
        " * rfork(2): the flag bits and the declaration.\n",
        " *\n",
        " * GENERATED by `cargo xtask rfork-header` from port/src/rfork.rs.\n",
        " * Do not edit; change the Rust constants and regenerate.\n",
        " *\n",
        " * RFNAMEG to RFNOMNT mirror Harvey sys/include/libc.h:613-624 and\n",
        " * the declaration mirrors libc.h:684.  RFNOMNT is defined by Harvey\n",
        " * and is not implemented by r9.  The flags after RFNOMNT are\n",
        " * reserved by r9 and are in no Harvey header.\n",
        " *\n",
        " * This header declares an anonymous enum; do not include it in a\n",
        " * translation unit that also includes Harvey's libc.h.\n",
        " */\n",
    ));
    out.push_str("enum\n{\n");
    let last = flags::ALL.len() - 1;
    for (i, (name, value)) in flags::ALL.iter().enumerate() {
        assert!(value.is_power_of_two(), "{name} is not a single bit");
        if i == flags::FIRST_R9_ONLY {
            out.push_str("\t/* r9 only: reserved, rejected by rfork until implemented */\n");
        }
        let tabs = if name.len() < 8 { "\t\t" } else { "\t" };
        let comma = if i == last { "" } else { "," };
        out.push_str(&format!("\t{name}{tabs}= (1<<{}){comma}\n", value.trailing_zeros()));
    }
    out.push_str("};\n\nextern\tint\trfork(int);\n");
    out
}

/// Write the rendering to `<workspace>/sys/include/rfork.h`, creating the
/// directory if needed.
pub fn write(workspace: &Path) -> Result<()> {
    let path = workspace.join(HEADER_PATH);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("rfork-header: create {}: {e}", parent.display()))?;
    }
    fs::write(&path, render())
        .map_err(|e| format!("rfork-header: write {}: {e}", path.display()))?;
    Ok(())
}

/// Fail when the committed `sys/include/rfork.h` differs from `render()`,
/// including when the file is absent or empty.
pub fn check(workspace: &Path) -> Result<()> {
    let path = workspace.join(HEADER_PATH);
    let committed = fs::read_to_string(&path).map_err(|e| {
        format!(
            "rfork-header: read {}: {e} (run `cargo xtask rfork-header`)",
            path.display()
        )
    })?;
    if committed != render() {
        return Err(format!(
            "rfork-header: {} is stale against port/src/rfork.rs (run `cargo xtask rfork-header`)",
            path.display()
        )
        .into());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::env;
    use std::path::PathBuf;
    use std::process;

    use super::*;

    fn scratch(name: &str) -> PathBuf {
        let dir = env::temp_dir().join(format!("r9-rforkh-{name}-{}", process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn rforkh_render_pins_harvey_lines() {
        let text = render();
        for line in [
            "\tRFNAMEG\t\t= (1<<0),",
            "\tRFENVG\t\t= (1<<1),",
            "\tRFFDG\t\t= (1<<2),",
            "\tRFNOTEG\t\t= (1<<3),",
            "\tRFPROC\t\t= (1<<4),",
            "\tRFMEM\t\t= (1<<5),",
            "\tRFNOWAIT\t= (1<<6),",
            "\tRFCNAMEG\t= (1<<10),",
            "\tRFCENVG\t\t= (1<<11),",
            "\tRFCFDG\t\t= (1<<12),",
            "\tRFREND\t\t= (1<<13),",
            "\tRFNOMNT\t\t= (1<<14),",
        ] {
            assert!(text.contains(line), "missing Harvey enumerator line {line:?}");
        }
        for line in [
            "\tRFCKEY\t\t= (1<<18),",
            "\tRFROBASE\t= (1<<19),",
            "\tRFRANDMEM\t= (1<<20),",
            "\tRFNOLEGACY\t= (1<<21)\n",
        ] {
            assert!(text.contains(line), "missing reserved enumerator line {line:?}");
        }
        assert!(text.ends_with("extern\tint\trfork(int);\n"), "missing the declaration");
    }

    #[test]
    fn rforkh_render_is_stable_and_ascending() {
        assert_eq!(render(), render());
        let mut previous = None;
        for line in render().lines() {
            if let Some(start) = line.find("= (1<<") {
                let rest = &line[start + "= (1<<".len()..];
                let end = rest.find(')').expect("enumerator shift is closed");
                let shift: u32 = rest[..end].parse().expect("enumerator shift is a number");
                if let Some(previous) = previous {
                    assert!(shift > previous, "enumerator shifts are not strictly increasing");
                }
                previous = Some(shift);
            }
        }
        assert!(previous.is_some(), "the rendering has enumerators");
    }

    #[test]
    fn rforkh_check_rejects_missing_empty_and_stale() {
        let dir = scratch("check");
        assert!(check(&dir).is_err(), "a missing header must be rejected");
        write(&dir).expect("write the header");
        assert!(check(&dir).is_ok(), "a freshly written header must match");
        let path = dir.join(HEADER_PATH);
        fs::write(&path, "").expect("empty the header");
        assert!(check(&dir).is_err(), "an empty header must be rejected");
        fs::write(&path, render().replace("(1<<21)", "(1<<22)")).expect("stale the header");
        assert!(check(&dir).is_err(), "a stale header must be rejected");
        write(&dir).expect("rewrite the header");
        assert!(check(&dir).is_ok(), "the rewritten header must match again");
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn rforkh_mutated_render_differs() {
        let mutated = render().replace("(1<<21)", "(1<<22)");
        assert_ne!(mutated, render(), "the mutation must apply");
    }

    /// The four arch files that must import every rfork flag from
    /// `port::rfork` (D-18), with the path each failure message names.
    const ARCH_SOURCES: [(&str, &str); 4] = [
        ("x86_64/src/proc.rs", include_str!("../../x86_64/src/proc.rs")),
        ("x86_64/src/syscall.rs", include_str!("../../x86_64/src/syscall.rs")),
        ("aarch64/src/syscall.rs", include_str!("../../aarch64/src/syscall.rs")),
        ("aarch64/src/proc.rs", include_str!("../../aarch64/src/proc.rs")),
    ];

    /// The one-definition invariant (DSGN-03, D-18): every rfork flag is
    /// defined in `port::rfork` and nowhere else, and each arch
    /// `syscall.rs` names its supported mask at module level (D-20) so
    /// the mask test can read it.  The forbidden patterns are built from
    /// separate pieces, so this test's own source never contains them.
    #[test]
    fn rfork_flags_have_one_definition() {
        let mut problems: Vec<String> = Vec::new();

        // 1. No arch source defines a flag constant again.
        let const_kw = ["con", "st "].concat();
        let rf_prefix = ["R", "F"].concat();
        let shift_ty = ["u6", "4 = 1 <<"].concat();
        for (file, text) in ARCH_SOURCES {
            for (n, line) in text.lines().enumerate() {
                let trimmed = line.trim_start();
                let rest = trimmed
                    .strip_prefix("pub(crate) ")
                    .or_else(|| trimmed.strip_prefix("pub "))
                    .unwrap_or(trimmed);
                let Some(rest) = rest.strip_prefix(&const_kw) else { continue };
                let Some((name, tail)) = rest.split_once(':') else { continue };
                if name.starts_with(rf_prefix.as_str()) && tail.trim_start().starts_with(&shift_ty) {
                    problems.push(format!(
                        "{file}:{}: defines an rfork flag constant; the one definition is port::rfork",
                        n + 1
                    ));
                }
            }
        }

        // 2. aarch64/src/proc.rs reaches no flag through the crate's
        // syscall module (a private import there is not visible to it).
        let through_syscall = ["crate::", "syscall::RF"].concat();
        for (file, text) in [ARCH_SOURCES[3]] {
            for (n, line) in text.lines().enumerate() {
                if line.contains(&through_syscall) {
                    problems.push(format!(
                        "{file}:{}: reaches a flag through the crate's syscall module; use port::rfork::",
                        n + 1
                    ));
                }
            }
        }

        // 3. Neither arch syscall.rs keeps a function-local mask.
        let local_mask = ["const ", "SUPPORTED", ": u64"].concat();
        for (file, text) in [ARCH_SOURCES[1], ARCH_SOURCES[2]] {
            for (n, line) in text.lines().enumerate() {
                if line.contains(&local_mask) {
                    problems.push(format!(
                        "{file}:{}: keeps a function-local supported mask; hoist it to RFORK_SUPPORTED",
                        n + 1
                    ));
                }
            }
        }

        // 4. Each arch syscall.rs declares the hoisted mask exactly once.
        let declaration = ["pub(crate) ", "const ", "RFORK_SUPPORTED", ": u64"].concat();
        for (file, text) in [ARCH_SOURCES[1], ARCH_SOURCES[2]] {
            let count = text.lines().filter(|line| line.contains(&declaration)).count();
            if count != 1 {
                problems.push(format!(
                    "{file}: expected exactly one `pub(crate) const RFORK_SUPPORTED: u64`, found {count}"
                ));
            }
        }

        // 5. No arch file re-exports a port::rfork name (D-18).
        let re_exports = [
            ["pub", " use port::rfork"].concat(),
            ["pub(crate)", " use port::rfork"].concat(),
        ];
        for (file, text) in ARCH_SOURCES {
            for (n, line) in text.lines().enumerate() {
                if re_exports.iter().any(|pattern| line.contains(pattern)) {
                    problems.push(format!(
                        "{file}:{}: re-exports a port::rfork name; make the import private (D-18)",
                        n + 1
                    ));
                }
            }
        }

        assert!(
            problems.is_empty(),
            "rfork flags must have one definition and each arch mask one name:\n{}",
            problems.join("\n")
        );
    }
}
